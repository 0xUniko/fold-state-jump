import { createHash } from 'node:crypto';
import { constants } from 'node:fs';
import { lstat, mkdir, mkdtemp, open, readFile, realpath, rmdir, stat, type FileHandle } from 'node:fs/promises';
import path from 'node:path';

export type CacheProject =
  | { readonly _tag: 'GitProject'; readonly root: string; readonly key: string }
  | { readonly _tag: 'UnreadableGitProject'; readonly root: string; readonly key: string; readonly reason: string }
  | { readonly _tag: 'WorkspaceProject'; readonly root: string; readonly key: string }
  | { readonly _tag: 'SourceDirectoryProject'; readonly root: string; readonly key: string };

export type CacheLocationInput = {
  readonly source: string;
  readonly workspaceRoots: readonly string[];
  readonly globalStorage: string;
  /** Absolute base directory, or a path relative to the selected project root. */
  readonly configuredPath?: string;
};

type PreferredCacheLocation =
  | { readonly _tag: 'ProjectLocalCache'; readonly project: CacheProject; readonly root: string; readonly astDirectory: string }
  | { readonly _tag: 'ConfiguredCache'; readonly project: CacheProject; readonly root: string; readonly astDirectory: string };

export type CacheLocation = PreferredCacheLocation
  | { readonly _tag: 'GlobalFallbackCache'; readonly project: CacheProject; readonly root: string; readonly astDirectory: string;
      readonly preferred: PreferredCacheLocation; readonly reason: string }
  | { readonly _tag: 'UnavailableCache'; readonly project: CacheProject; readonly preferred: PreferredCacheLocation;
      readonly reason: string };

export const cacheGitignore = '# This file is autogenerated by fold-state-jump.\n*\n';

const absolute = (directory: string): string => {
  if (!path.isAbsolute(directory)) throw new Error('Cache location requires an absolute path: ' + directory);
  return path.normalize(directory);
};
const canonical = async (directory: string): Promise<string> => realpath(absolute(directory)).catch(() => absolute(directory));
const ancestors = (directory: string): readonly string[] => {
  const root = path.parse(directory).root;
  return directory.slice(root.length).split(path.sep).filter(Boolean).reduce<readonly string[]>(
    (directories, part) => [path.join(directories[0]!, part), ...directories], [root]);
};
const contains = (directory: string, source: string): boolean => {
  const relative = path.relative(directory, source);
  return relative !== '..' && !relative.startsWith('..' + path.sep) && !path.isAbsolute(relative);
};
type GitMetadata = { readonly _tag: 'VerifiedGitMetadata' }
  | { readonly _tag: 'UnreadableGitMetadata'; readonly reason: string }
  | { readonly _tag: 'NoGitMetadata' };
const noGitMetadata: GitMetadata = { _tag: 'NoGitMetadata' };
const missingPath = (error: unknown): boolean => error !== null && typeof error === 'object' && 'code' in error &&
  (error.code === 'ENOENT' || error.code === 'ENOTDIR');
const inspectGitMetadata = async (directory: string): Promise<GitMetadata> => {
  const markerPath = path.join(directory, '.git');
  try {
    const marker = await lstat(markerPath);
    const gitDirectory = marker.isDirectory() ? markerPath
      : marker.isFile() ? (await readFile(markerPath, 'utf8')).match(/^gitdir: ([^\r\n]+)\r?\n?$/)?.[1]
      : undefined;
    if (gitDirectory === undefined) return noGitMetadata;
    const head = await stat(path.join(path.resolve(directory, gitDirectory), 'HEAD'));
    return head.isFile() ? { _tag: 'VerifiedGitMetadata' } : noGitMetadata;
  } catch (error) {
    return missingPath(error) ? noGitMetadata : { _tag: 'UnreadableGitMetadata', reason: String(error) };
  }
};
const gitProject = async (directory: string): Promise<CacheProject | undefined> => ancestors(directory).reduce<Promise<CacheProject | undefined>>(
  async (selected, directory) => {
    const project = await selected;
    if (project !== undefined) return project;
    const metadata = await inspectGitMetadata(directory);
    switch (metadata._tag) {
      case 'VerifiedGitMetadata': return { _tag: 'GitProject', root: directory, key: projectKey(directory) };
      case 'UnreadableGitMetadata': return { _tag: 'UnreadableGitProject', root: directory, key: projectKey(directory), reason: metadata.reason };
      case 'NoGitMetadata': return undefined;
    }
  }, Promise.resolve(undefined));

/** No process cwd, compilation database cwd, or Git common directory participates. */
export const resolveCacheProject = async (source: string, workspaceRoots: readonly string[]): Promise<CacheProject> => {
  const sourceDirectory = await canonical(path.dirname(absolute(source)));
  const project = await gitProject(sourceDirectory);
  if (project !== undefined) return project;
  const roots = await Promise.all(workspaceRoots.map(canonical));
  const workspaceRoot = roots.filter((root) => contains(root, sourceDirectory))
    .sort((left, right) => right.length - left.length || left.localeCompare(right))[0];
  return workspaceRoot === undefined
    ? { _tag: 'SourceDirectoryProject', root: sourceDirectory, key: projectKey(sourceDirectory) }
    : { _tag: 'WorkspaceProject', root: workspaceRoot, key: projectKey(workspaceRoot) };
};

const projectKey = (root: string): string => createHash('sha256').update(root).digest('hex');

const prepareIgnore = async (root: string): Promise<void> => {
  // Create only when absent; never truncate an existing (possibly user-owned) file.
  // A nonstandard ignore file could expose AST artifacts to Git, so use the
  // project-scoped global fallback instead of modifying it or trusting its rules.
  const ignorePath = path.join(root, '.gitignore');
  try {
    const ignore = await open(ignorePath, constants.O_WRONLY | constants.O_CREAT | constants.O_EXCL | constants.O_NOFOLLOW, 0o600);
    try { await ignore.writeFile(cacheGitignore); }
    finally { await ignore.close(); }
  } catch (error) {
    if (error === null || typeof error !== 'object' || !('code' in error) || error.code !== 'EEXIST') throw error;
    // Non-regular paths (for example a FIFO) must reach the stat rejection
    // without blocking while waiting for a writer.
    const ignore = await open(ignorePath, constants.O_RDONLY | constants.O_NOFOLLOW | constants.O_NONBLOCK);
    try {
      if (!(await ignore.stat()).isFile() || await ignore.readFile('utf8') !== cacheGitignore)
        throw new Error('Existing cache .gitignore has custom contents; leaving it unchanged');
    } finally { await ignore.close(); }
  }
};
const makeDirectory = (directory: string): Promise<void> => mkdir(directory, { mode: 0o700 }).catch((error: NodeJS.ErrnoException) => {
  if (error.code !== 'EEXIST') throw error;
});
const linuxDirectoryPath = (root: FileHandle): string => '/proc/self/fd/' + root.fd;
const openLinuxDirectory = (root: string): Promise<FileHandle> =>
  absolute(root).split(path.sep).filter(Boolean).reduce<Promise<FileHandle>>(async (root, component) => {
    const rootHandle = await root;
    try {
      const rootPath = path.join(linuxDirectoryPath(rootHandle), component);
      await makeDirectory(rootPath);
      return await open(rootPath, constants.O_RDONLY | constants.O_DIRECTORY | constants.O_NOFOLLOW);
    } finally { await rootHandle.close(); }
  }, open('/', constants.O_RDONLY | constants.O_DIRECTORY));
const prepareDirectory = async (root: string): Promise<void> => {
  if (process.platform === 'linux') {
    const rootHandle = await openLinuxDirectory(root);
    try {
      const rootPath = linuxDirectoryPath(rootHandle);
      await prepareIgnore(rootPath);
      await makeDirectory(path.join(rootPath, 'ast'));
      const astHandle = await open(path.join(rootPath, 'ast'), constants.O_RDONLY | constants.O_DIRECTORY | constants.O_NOFOLLOW);
      try {
        // The probe stays relative to the held directory even if another
        // process replaces a cache path while preparation is in flight.
        const probe = await mkdtemp(path.join(linuxDirectoryPath(astHandle), '.write-probe-'));
        await rmdir(probe);
      } finally { await astHandle.close(); }
    } finally { await rootHandle.close(); }
    return;
  }
  // Other platforms keep the existing AST support and reject directory
  // symlinks at preparation. Unlike Linux's fd anchors, these checks cannot
  // exclude a concurrent parent-directory replacement after lstat.
  await [...ancestors(absolute(root))].reverse().reduce<Promise<void>>(async (prepared, root) => {
    await prepared;
    await makeDirectory(root);
    const metadata = await lstat(root);
    if (!metadata.isDirectory() || metadata.isSymbolicLink()) throw new Error('Unsafe cache directory');
  }, Promise.resolve());
  await prepareIgnore(root);
  const astDirectory = path.join(root, 'ast');
  await makeDirectory(astDirectory);
  const metadata = await lstat(astDirectory);
  if (!metadata.isDirectory() || metadata.isSymbolicLink()) throw new Error('Unsafe AST cache directory');
  const probe = await mkdtemp(path.join(astDirectory, '.write-probe-'));
  await rmdir(probe);
};

/** Custom/global bases are namespaced by canonical project root, including worktrees. */
export const prepareCacheLocation = async (input: CacheLocationInput): Promise<CacheLocation> => {
  const project = await resolveCacheProject(input.source, input.workspaceRoots);
  const configuredPath = input.configuredPath?.trim();
  const root = configuredPath
    ? path.join(path.resolve(project.root, configuredPath), project.key)
    : path.join(project.root, '.cache', 'fold-state-jump');
  const preferred: PreferredCacheLocation = configuredPath
    ? { _tag: 'ConfiguredCache', project, root, astDirectory: path.join(root, 'ast') }
    : { _tag: 'ProjectLocalCache', project, root, astDirectory: path.join(root, 'ast') };
  try {
    await prepareDirectory(root);
    return preferred;
  } catch (error) {
    const reason = String(error);
    const fallbackRoot = path.join(absolute(input.globalStorage), 'project-cache-v2', project.key);
    try {
      await prepareDirectory(fallbackRoot);
      return { _tag: 'GlobalFallbackCache', project, root: fallbackRoot, astDirectory: path.join(fallbackRoot, 'ast'), preferred, reason };
    } catch (error) {
      return { _tag: 'UnavailableCache', project, preferred, reason: reason + '; global fallback: ' + String(error) };
    }
  }
};
